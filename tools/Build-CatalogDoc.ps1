<#
.SYNOPSIS
    Writes docs\CATALOG.md from tweaks\*.json and data\apps.json, so the published list of
    settings can never drift from what PitCrew actually ships. Run it after changing the catalog.
#>
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
. (Join-Path $root 'src\Load.ps1')
Initialize-PcContext -Root $root -Language 'en'

$evidenceText = @{ learn = 'Microsoft Learn'; vendor = 'vendor docs'; community = 'community' }
$sections = [ordered]@{ performance = 'Performance'; privacy = 'Privacy'; explorer = 'Explorer & taskbar' }
$tweaks = @(Import-PcTweaks)

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('# Catalog')
$lines.Add('')
$lines.Add('Generated by `tools\Build-CatalogDoc.ps1` from `tweaks\*.json` and `data\apps.json`; do not edit by hand.')
$lines.Add("What's planned next is in [TWEAKS.md](TWEAKS.md); what is left out on purpose is in [NOT-INCLUDED.md](NOT-INCLUDED.md).")
$lines.Add('')
$lines.Add(('{0} settings and {1} removable apps.' -f $tweaks.Count, @(Get-PcAppCatalog).Count))

foreach ($category in $sections.Keys) {
    $items = @($tweaks | Where-Object category -eq $category)
    if ($items.Count -eq 0) { continue }
    $lines.Add('')
    $lines.Add("## $($sections[$category]) ($($items.Count))")
    $lines.Add('')
    $lines.Add('| Setting | Risk | Scope | Source | Notes |')
    $lines.Add('|---|---|---|---|---|')
    foreach ($t in $items) {
        $notes = @()
        if ($t.appliesTo.editions) { $notes += 'editions: ' + (@($t.appliesTo.editions) -join ', ') }
        if ($t.appliesTo.formFactor) { $notes += "$($t.appliesTo.formFactor) only" }
        if ($t.appliesTo.minBuild) { $notes += "build $($t.appliesTo.minBuild)+" }
        if ($t.requires.restart) { $notes += 'restart' }
        if ($t.requires.signOut) { $notes += 'sign-out' }
        if ($t.requires.restartExplorer) { $notes += 'restarts Explorer' }
        $title = (Resolve-PcLocalized $t.title) -replace '\|', '\|'
        $lines.Add(('| {0} <br><sub>`{1}`</sub> | {2} | {3} | [{4}]({5}) | {6} |' -f $title, $t.id, $t.risk, $t.scope, $evidenceText[$t.evidence], $t.reference, ($notes -join ', ')))
    }
}

$apps = @(Get-PcAppCatalog)
$lines.Add('')
$lines.Add("## Built-in apps ($($apps.Count))")
$lines.Add('')
$lines.Add('Removed for the current user only; each can be reinstalled from the Microsoft Store.')
$lines.Add('')
$lines.Add('| App | Package | Store ID | Label |')
$lines.Add('|---|---|---|---|')
foreach ($a in $apps) {
    $label = if ($a.risk -eq 'caution') { 'read before removing: ' + (Resolve-PcLocalized $a.note) } else { 'safe' }
    $lines.Add(('| {0} | `{1}` | {2} | {3} |' -f (Resolve-PcLocalized $a.name), $a.package, $a.storeId, $label))
}

$out = Join-Path $root 'docs\CATALOG.md'
[IO.File]::WriteAllText($out, (($lines -join "`n") + "`n"), (New-Object Text.UTF8Encoding $false))
Write-Host "Wrote $out ($($tweaks.Count) settings, $($apps.Count) apps)"
